// Helper to generate staggered ISO timestamps over the past 1-14 days
const daysAgo = (days: number, hoursOffset = 0): string => {
  const ms = (days * 24 + hoursOffset) * 60 * 60 * 1000;
  return new Date(Date.now() - ms).toISOString();
};

